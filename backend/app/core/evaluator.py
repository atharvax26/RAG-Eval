from ragas import evaluate
from ragas.metrics import (
    context_precision,
    context_recall,
    faithfulness,
    answer_relevancy,
)
from datasets import Dataset
from typing import List, Optional

METRICS = [context_precision, context_recall, faithfulness, answer_relevancy]


def run_ragas(
    questions: List[str],
    answers: List[str],
    contexts: List[List[str]],
    ground_truths: Optional[List[str]] = None,
) -> dict:
    """
    questions    : list[str]
    answers      : list[str] — generated by Gemini
    contexts     : list[list[str]] — retrieved chunks per question
    ground_truths: list[str] | None — optional; if None use empty strings
    """
    # IMPORTANT: RAGAS uses the GEMINI_API_KEY env var automatically
    # Set it before calling run_ragas().
    # contexts must be list[list[str]] — one inner list per question.
    if ground_truths is None:
        ground_truths = [''] * len(questions)

    dataset = Dataset.from_dict({
        'question': questions,
        'answer': answers,
        'contexts': contexts,
        'ground_truth': ground_truths,
    })

    result = evaluate(dataset, metrics=METRICS)
    return {
        'context_precision': float(result['context_precision']),
        'context_recall': float(result['context_recall']),
        'faithfulness': float(result['faithfulness']),
        'answer_relevancy': float(result['answer_relevancy']),
    }
